import {
  FACT_CACHE_WINDOW_MS,
  LOCK_LEASE_MS,
  WAIT_MAX_MS,
  WAIT_POLL_INTERVAL_MS,
} from "./constants";

export type StoredFact = {
  id: string;
  userId: string;
  movie: string;
  content: string;
  createdAt: Date;
};

/**
 * Persistence operations the service needs. Every method is scoped by userId;
 * there is deliberately no way to look up a fact without one.
 */
export interface FactRepository {
  getFavoriteMovie(userId: string): Promise<string | null | undefined>; // undefined = no such user
  findLatestFact(userId: string, movie: string): Promise<StoredFact | null>;
  createFact(data: Omit<StoredFact, "id">): Promise<StoredFact>;
  /** Atomically take the user's lease if it is free or expired. */
  tryAcquireLock(userId: string, token: string, now: Date, expiresAt: Date): Promise<boolean>;
  /** Release the lease only if we still own it (token matches). */
  releaseLock(userId: string, token: string): Promise<void>;
}

export type FactServiceDeps = {
  repo: FactRepository;
  generateFact: (movie: string) => Promise<string>;
  now: () => Date;
  sleep: (ms: number) => Promise<void>;
  newToken: () => string;
  logError?: (message: string, error: unknown) => void;
};

/**
 * Where the returned fact came from:
 * - cache:          latest fact is < 60s old
 * - generated:      a new fact was generated by this request
 * - stale_fallback: generation failed (OpenAI error/timeout); serving the latest older fact
 * - in_progress:    another request is generating right now; serving the latest older
 *                   fact, or the one it just produced
 */
export type FactSource = "cache" | "generated" | "stale_fallback" | "in_progress";

export type FactErrorCode =
  | "USER_NOT_FOUND"
  | "NO_FAVORITE_MOVIE"
  | "GENERATION_FAILED"
  | "GENERATION_IN_PROGRESS";

export type FactResult =
  | { ok: true; fact: StoredFact; source: FactSource }
  | { ok: false; error: FactErrorCode };

export function isFresh(fact: StoredFact, now: Date): boolean {
  // Strictly "less than 60 seconds old" is cached; at exactly 60s we regenerate.
  return now.getTime() - fact.createdAt.getTime() < FACT_CACHE_WINDOW_MS;
}

/**
 * Returns a fun fact about the user's favorite movie, honoring the 60s cache
 * window and guaranteeing at most one in-flight generation per user.
 *
 *   1. Fresh fact (< 60s) exists              -> return it (no lock, no OpenAI)
 *   2. Try to acquire the per-user lease
 *      a. acquired: re-check freshness (another request may have just
 *         finished), else generate + store. On failure fall back to the latest
 *         stale fact, or report an error. Always release the lease.
 *      b. not acquired (someone else is generating):
 *         - have an older fact -> return it right away (don't block the user)
 *         - no fact at all     -> poll briefly for the in-flight result
 */
export async function getFactForUser(userId: string, deps: FactServiceDeps): Promise<FactResult> {
  const { repo } = deps;

  const movie = await repo.getFavoriteMovie(userId);
  if (movie === undefined) return { ok: false, error: "USER_NOT_FOUND" };
  if (!movie) return { ok: false, error: "NO_FAVORITE_MOVIE" };

  const latest = await repo.findLatestFact(userId, movie);
  if (latest && isFresh(latest, deps.now())) {
    return { ok: true, fact: latest, source: "cache" };
  }

  const token = deps.newToken();
  const lockNow = deps.now();
  const acquired = await repo.tryAcquireLock(
    userId,
    token,
    lockNow,
    new Date(lockNow.getTime() + LOCK_LEASE_MS),
  );

  if (!acquired) {
    if (latest) return { ok: true, fact: latest, source: "in_progress" };
    return waitForInFlightFact(userId, movie, deps);
  }

  try {
    // Double-check under the lease: a concurrent request may have generated a
    // fact between our first read and acquiring the lease.
    const recheck = await repo.findLatestFact(userId, movie);
    if (recheck && isFresh(recheck, deps.now())) {
      return { ok: true, fact: recheck, source: "cache" };
    }

    let content: string;
    try {
      content = await deps.generateFact(movie);
    } catch (error) {
      deps.logError?.("Fact generation failed", error);
      const fallback = recheck ?? latest;
      if (fallback) return { ok: true, fact: fallback, source: "stale_fallback" };
      return { ok: false, error: "GENERATION_FAILED" };
    }

    const fact = await repo.createFact({ userId, movie, content, createdAt: deps.now() });
    return { ok: true, fact, source: "generated" };
  } finally {
    await repo.releaseLock(userId, token);
  }
}

async function waitForInFlightFact(
  userId: string,
  movie: string,
  deps: FactServiceDeps,
): Promise<FactResult> {
  const attempts = Math.ceil(WAIT_MAX_MS / WAIT_POLL_INTERVAL_MS);
  for (let i = 0; i < attempts; i++) {
    await deps.sleep(WAIT_POLL_INTERVAL_MS);
    const fact = await deps.repo.findLatestFact(userId, movie);
    if (fact) return { ok: true, fact, source: "in_progress" };
  }
  return { ok: false, error: "GENERATION_IN_PROGRESS" };
}
